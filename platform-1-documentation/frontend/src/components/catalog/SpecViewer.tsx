import React, { useState } from 'react';
import { Endpoint } from '../../types/schema';
import { Copy, Check, ShieldCheck, AlertTriangle, FileDown, ArrowDownLeft, ArrowUpRight, Smartphone, Server } from 'lucide-react';
import { useLanguage } from '../../i18n';

interface SpecViewerProps {
  endpoint: Endpoint;
  onOpenErrorDictionary?: () => void;
}

export const SpecViewer: React.FC<SpecViewerProps> = ({ 
  endpoint,
  onOpenErrorDictionary
}) => {
  const [activeTab, setActiveTab] = useState<'doc' | 'example'>('doc');
  const [currentExampleFormat, setCurrentExampleFormat] = useState<'json' | 'xml' | 'yaml'>('json');
  const [copiedPath, setCopiedPath] = useState(false);
  const [copiedCurl, setCopiedCurl] = useState(false);
  const [copiedReq, setCopiedReq] = useState(false);
  const [copiedRes, setCopiedRes] = useState(false);

  const { t, language } = useLanguage();
  const isEn = language === 'en';

  const handleDownloadSpec = () => {
    const specData = {
      $schema: 'https://api.gov.fintech/schemas/v1/ultimate-pay-spec.json',
      version: 'v2026.2',
      exportedAt: new Date().toISOString(),
      endpoint: {
        method: endpoint.method,
        path: endpoint.path,
        shortName: endpoint.shortName,
        desc: endpoint.desc,
        descEn: endpoint.descEn,
        headers: endpoint.params || [],
        businessRules: endpoint.rules || [],
        payload: endpoint.payload,
        res200: endpoint.res200,
        res422: endpoint.res422
      }
    };

    const blob = new Blob([JSON.stringify(specData, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${endpoint.shortName || 'endpoint'}-spec.json`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleCopy = (text: string, type: 'path' | 'curl' | 'req' | 'res') => {
    navigator.clipboard.writeText(text);
    if (type === 'path') {
      setCopiedPath(true);
      setTimeout(() => setCopiedPath(false), 2000);
    } else if (type === 'curl') {
      setCopiedCurl(true);
      setTimeout(() => setCopiedCurl(false), 2000);
    } else if (type === 'req') {
      setCopiedReq(true);
      setTimeout(() => setCopiedReq(false), 2000);
    } else if (type === 'res') {
      setCopiedRes(true);
      setTimeout(() => setCopiedRes(false), 2000);
    }
  };

  const standardHeaders = isEn ? [
    { name: 'Authorization', type: 'string (Bearer Token)', req: 'Mandatory', desc: 'Authorized OAuth 2.0 / FAPI 1.0 Advanced token issued by central identity gateway' },
    { name: 'X-Idempotency-Key', type: 'string (UUIDv4)', req: 'Strict Mandatory', desc: 'Idempotency key generated by banking core to prevent duplicate posting on network drops' },
    { name: 'X-Signature', type: 'string (Base64 RSA)', req: 'Financial Required', desc: 'Digital payload signature created with financial institution RSA-PSS 4096 private key' },
    { name: 'X-Correlation-ID', type: 'string (UUID)', req: 'Audit Required', desc: 'End-to-end tracing identifier correlating originating bank and central clearing switch' }
  ] : [
    { name: 'Authorization', type: 'string (Bearer Token)', req: 'إلزامي', desc: 'رمز تفويض مصادق عليه عبر مزود الهوية المعتمد OAuth 2.0 / FAPI 1.0 Advanced' },
    { name: 'X-Idempotency-Key', type: 'string (UUIDv4)', req: 'إلزامي قطعي', desc: 'مفتاح عدم التكرار الصادر من نظام البنك لمنع ازدواجية الخصم والقيد عند انقطاع الشبكة' },
    { name: 'X-Signature', type: 'string (Base64 RSA)', req: 'إلزامي للعمليات المالية', desc: 'التوقيع الرقمي لمحتوى الطلب باستخدام مفتاح البنك الخاص RSA-PSS 4096' },
    { name: 'X-Correlation-ID', type: 'string (UUID)', req: 'إلزامي للتدقيق', desc: 'معرف التتبع الشامل لمطابقة مسار العملية بين البنك المرسل والشبكة المركزية' }
  ];

  const responseFields = endpoint.responseFields || (isEn ? [
    { name: 'status', type: 'string (Enum)', req: 'Guaranteed', desc: 'Clearing processing state: SUCCESS, PENDING, or REJECTED' },
    { name: 'transactionId', type: 'string (UUID/Ref)', req: 'Guaranteed', desc: 'National unique settlement identifier certified by central authority' },
    { name: 'clearingCode', type: 'string', req: 'Conditional', desc: 'Instant clearing session clearing reference code' },
    { name: 'timestamp', type: 'string (ISO-8601)', req: 'Guaranteed', desc: 'Precise millisecond timestamp certifying financial ledger booking' }
  ] : [
    { name: 'status', type: 'string (Enum)', req: 'مؤكد بالرد', desc: 'حالة تنفيذ العملية في المقاصة: SUCCESS أو PENDING أو REJECTED' },
    { name: 'transactionId', type: 'string (UUID/Ref)', req: 'مؤكد بالرد', desc: 'المعرف الرقمي الوطني الثابت للحوالة المعتمدة لدى البنك المركزي' },
    { name: 'clearingCode', type: 'string', req: 'شرطي', desc: 'رمز جلسة التسوية المركزية الفورية الصادر من نظام المقاصة اللحظية' },
    { name: 'timestamp', type: 'string (ISO-8601)', req: 'مؤكد بالرد', desc: 'التوقيت الزمني الدقيق بالمللي ثانية لتوثيق القيد المالي' }
  ]);

  const getFormattedPayload = () => {
    if (currentExampleFormat === 'xml') {
      return `<?xml version="1.0" encoding="UTF-8"?>\n<TransferRequest>\n  <SourceAccount>SA0380000000608010167519</SourceAccount>\n  <DestinationAccount>SA4420000001234567890123</DestinationAccount>\n  <Amount>1500.00</Amount>\n  <Currency>SAR</Currency>\n  <IdempotencyKey>9b1deb4d-3b7d-4bad-9bdd-2b0d7b3dcb6d</IdempotencyKey>\n</TransferRequest>`;
    }
    if (currentExampleFormat === 'yaml') {
      return `sourceAccount: "SA0380000000608010167519"\ndestinationAccount: "SA4420000001234567890123"\namount: 1500.00\ncurrency: "SAR"\nidempotencyKey: "9b1deb4d-3b7d-4bad-9bdd-2b0d7b3dcb6d"`;
    }
    return endpoint.payload || `{\n  "sourceAccount": "SA0380000000608010167519",\n  "destinationAccount": "SA4420000001234567890123",\n  "amount": 1500.00,\n  "currency": "SAR",\n  "idempotencyKey": "9b1deb4d-3b7d-4bad-9bdd-2b0d7b3dcb6d"\n}`;
  };

  const getFormattedResponse = () => {
    if (currentExampleFormat === 'xml') {
      return `<?xml version="1.0" encoding="UTF-8"?>\n<TransferResponse>\n  <Status>SUCCESS</Status>\n  <TransactionId>TXN-88492019</TransactionId>\n  <ClearingCode>SA-IPS-CLR-01</ClearingCode>\n  <SettledAt>2026-10-11T12:00:00Z</SettledAt>\n</TransferResponse>`;
    }
    if (currentExampleFormat === 'yaml') {
      return `status: "SUCCESS"\ntransactionId: "TXN-88492019"\nclearingCode: "SA-IPS-CLR-01"\nsettledAt: "2026-10-11T12:00:00Z"`;
    }
    return endpoint.res200 || `{\n  "status": "SUCCESS",\n  "transactionId": "TXN-88492019",\n  "clearingCode": "SA-IPS-CLR-01",\n  "settledAt": "2026-10-11T12:00:00Z"\n}`;
  };

  return (
    <div className="spec-workbench-container">
      {/* Ultra-Slim Consolidated Single-Row Header Bar (42px) */}
      <div className="spec-slim-toolbar">
        <div className="spec-slim-meta">
          <div className="spec-slim-path-wrap" style={{ display: 'flex', alignItems: 'center', gap: '0.5rem', flexWrap: 'wrap' }}>
            <span className={`method-badge method-${endpoint.method.toLowerCase()}`}>
              {endpoint.method}
            </span>
            <span className="mono spec-slim-path" dir="ltr" style={{ unicodeBidi: 'isolate' }}>
              {endpoint.path}
            </span>

            {endpoint.isDraft ? (
              <span className="badge-pill badge-opt" style={{ borderColor: 'var(--amber)', color: 'var(--amber)' }}>
                <ShieldCheck size={12} /> {isEn ? 'Screen Draft v2026.2' : 'مسودة مضافة من الشاشة'}
              </span>
            ) : (
              <span className="badge-pill badge-iso">
                <ShieldCheck size={12} /> {isEn ? 'Official Certified v2026.2' : 'معتمد رسمي v2026.2'}
              </span>
            )}

            {/* Direction Pill */}
            {endpoint.direction && (
              <span className="badge-pill" style={{
                background: endpoint.direction === 'INBOUND' ? 'rgba(56, 189, 248, 0.12)' : 'rgba(245, 158, 11, 0.12)',
                color: endpoint.direction === 'INBOUND' ? 'var(--cyan)' : 'var(--amber)',
                borderColor: endpoint.direction === 'INBOUND' ? 'rgba(56, 189, 248, 0.25)' : 'rgba(245, 158, 11, 0.25)',
                display: 'inline-flex',
                alignItems: 'center',
                gap: '3px'
              }}>
                {endpoint.direction === 'INBOUND' ? (
                  <><ArrowDownLeft size={11} /> {isEn ? 'Inbound' : 'وارد'}</>
                ) : (
                  <><ArrowUpRight size={11} /> {isEn ? 'Outbound' : 'صادر'}</>
                )}
              </span>
            )}

            {/* Channels Pill */}
            {endpoint.channels && endpoint.channels.length > 0 && (
              <span className="badge-pill" style={{
                background: 'rgba(16, 185, 129, 0.12)',
                color: 'var(--emerald)',
                borderColor: 'rgba(16, 185, 129, 0.25)',
                display: 'inline-flex',
                alignItems: 'center',
                gap: '3px'
              }}>
                {endpoint.channels.includes('MOBILE') ? <Smartphone size={11} /> : <Server size={11} />}
                {endpoint.channels.includes('MOBILE') ? (isEn ? 'Mobile' : 'موبايل') : (isEn ? 'Server' : 'خوادم')}
              </span>
            )}

            <button 
              className="btn-slim-action" 
              onClick={() => handleCopy(endpoint.path, 'path')} 
              title={t('spec.copyEndpoint')}
            >
              {copiedPath ? <Check size={13} style={{ color: 'var(--emerald)' }} /> : <Copy size={13} />}
            </button>
          </div>
        </div>

        <div className="spec-slim-controls">
          {activeTab === 'example' && (
            <div className="spec-format-switcher">
              <button 
                className={`format-mini-btn ${currentExampleFormat === 'json' ? 'active' : ''}`}
                onClick={() => setCurrentExampleFormat('json')}
              >
                JSON
              </button>
              <button 
                className={`format-mini-btn ${currentExampleFormat === 'xml' ? 'active' : ''}`}
                onClick={() => setCurrentExampleFormat('xml')}
              >
                XML
              </button>
              <button 
                className={`format-mini-btn ${currentExampleFormat === 'yaml' ? 'active' : ''}`}
                onClick={() => setCurrentExampleFormat('yaml')}
              >
                YAML
              </button>
            </div>
          )}

          {/* Compact Segmented Control (Tabs) */}
          <div className="spec-slim-segmented">
            <button 
              className={`spec-slim-seg-btn ${activeTab === 'doc' ? 'active' : ''}`}
              onClick={() => setActiveTab('doc')}
            >
              <span>{isEn ? '1. Specification Tables' : '1. جداول المواصفة'}</span>
            </button>
            <button 
              className={`spec-slim-seg-btn ${activeTab === 'example' ? 'active' : ''}`}
              onClick={() => setActiveTab('example')}
            >
              <span>{isEn ? '2. Full Wire Examples' : '2. أمثلة الاستدعاء الكاملة'}</span>
            </button>
          </div>

          <button 
            className="btn btn-ghost btn-slim-action" 
            onClick={() => handleCopy(endpoint.curl || '', 'curl')} 
            title={t('spec.copyCurl')}
          >
            {copiedCurl ? <Check size={13} style={{ color: 'var(--emerald)' }} /> : <Copy size={13} />}
          </button>

          <button 
            className="btn btn-ghost btn-slim-action" 
            onClick={handleDownloadSpec} 
            title={t('docHub.exportEndpointJson')}
            style={{ color: 'var(--blue)' }}
          >
            <FileDown size={13} />
          </button>
        </div>
      </div>

      {/* PANE 1: SPECIFICATION TABLES (HEADERS -> REQUEST -> RESPONSE -> ERRORS) */}
      {activeTab === 'doc' && (
        <div className="spec-tables-stack">
          {/* 1. Headers Table Block */}
          <div className="spec-table-block">
            <div className="spec-table-block-header">
              <div className="spec-table-block-title">
                <span>{isEn ? 'Mandatory Request & Security Headers' : 'ترويسات الطلب والأمان الإلزامية (Request Headers)'}</span>
              </div>
              <span className="badge-pill badge-iso">Mandatory Security</span>
            </div>
            <div style={{ overflowX: 'auto' }}>
              <table className="spec-data-table">
                <thead>
                  <tr>
                    <th style={{ width: '25%' }}>{t('spec.headerName')}</th>
                    <th style={{ width: '20%' }}>{t('spec.headerType')}</th>
                    <th style={{ width: '15%' }}>{t('spec.headerReq')}</th>
                    <th style={{ width: '40%' }}>{t('spec.headerDesc')}</th>
                  </tr>
                </thead>
                <tbody>
                  {standardHeaders.map((h, i) => (
                    <tr key={i}>
                      <td><code className="mono spec-code-key">{h.name}</code></td>
                      <td><span className="mono" style={{ fontSize: '0.75rem', color: 'var(--text-dim)' }}>{h.type}</span></td>
                      <td>
                        <span className={`badge-pill ${h.req.includes('Strict') || h.req.includes('قطعي') ? 'badge-req' : 'badge-fin'}`}>
                          {h.req}
                        </span>
                      </td>
                      <td style={{ color: 'var(--text-muted)', fontSize: '0.78rem' }}>{h.desc}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>

          {/* 2. Request Body Table Block */}
          <div className="spec-table-block">
            <div className="spec-table-block-header">
              <div className="spec-table-block-title">
                <span>{isEn ? 'Request Body Schema' : 'حقول جسم الطلب (Request Body Schema)'}</span>
              </div>
              <span className="mono" style={{ fontSize: '0.75rem', color: 'var(--text-dim)' }}>Content-Type: application/json</span>
            </div>
            <div style={{ overflowX: 'auto' }}>
              <table className="spec-data-table">
                <thead>
                  <tr>
                    <th style={{ width: '25%' }}>{t('spec.paramName')}</th>
                    <th style={{ width: '20%' }}>{t('spec.paramType')}</th>
                    <th style={{ width: '15%' }}>{t('spec.paramReq')}</th>
                    <th style={{ width: '40%' }}>{t('spec.paramRule')}</th>
                  </tr>
                </thead>
                <tbody>
                  {endpoint.params && endpoint.params.length > 0 ? (
                    endpoint.params.map((param, i) => (
                      <tr key={i}>
                        <td><code className="mono spec-code-key">{param.name}</code></td>
                        <td><span className="mono" style={{ fontSize: '0.75rem', color: 'var(--text-dim)' }}>{param.type}</span></td>
                        <td>
                          <span className={`badge-pill ${param.req ? 'badge-req' : 'badge-opt'}`} style={{ marginInlineEnd: '0.35rem' }}>
                            {param.req ? t('spec.reqTrue') : t('spec.reqFalse')}
                          </span>
                          <span className={`badge-pill ${param.tagClass || 'badge-iso'}`}>
                            {param.tag}
                          </span>
                        </td>
                        <td style={{ color: 'var(--text-muted)', fontSize: '0.78rem' }}>{param.rule}</td>
                      </tr>
                    ))
                  ) : (
                    <tr>
                      <td colSpan={4} style={{ textAlign: 'center', color: 'var(--text-dim)', padding: '1.25rem' }}>
                        {isEn ? 'No request body required for this endpoint.' : 'لا يتطلب هذا المسار بيانات في جسم الطلب (No Request Body)'}
                      </td>
                    </tr>
                  )}
                </tbody>
              </table>
            </div>
          </div>

          {/* 3. Response Body Table Block */}
          <div className="spec-table-block">
            <div className="spec-table-block-header">
              <div className="spec-table-block-title">
                <span>{isEn ? 'Response Body Schema — HTTP 200 OK' : 'حقول استجابة النجاح (Response Body Schema — HTTP 200 OK)'}</span>
              </div>
              <span className="badge-pill badge-fin">Status: 200 OK</span>
            </div>
            <div style={{ overflowX: 'auto' }}>
              <table className="spec-data-table">
                <thead>
                  <tr>
                    <th style={{ width: '25%' }}>{isEn ? 'Attribute' : 'حقل الاستجابة (Attribute)'}</th>
                    <th style={{ width: '20%' }}>{t('spec.paramType')}</th>
                    <th style={{ width: '15%' }}>{t('spec.paramReq')}</th>
                    <th style={{ width: '40%' }}>{isEn ? 'Banking System Semantic' : 'المعنى والدلالة في النظام المصرفي'}</th>
                  </tr>
                </thead>
                <tbody>
                  {responseFields.map((f, i) => (
                    <tr key={i}>
                      <td><code className="mono" style={{ color: 'var(--emerald)', fontWeight: 700 }}>{f.name}</code></td>
                      <td><span className="mono" style={{ fontSize: '0.75rem', color: 'var(--text-dim)' }}>{f.type}</span></td>
                      <td><span className="badge-pill badge-fin">{f.req}</span></td>
                      <td style={{ color: 'var(--text-muted)', fontSize: '0.78rem' }}>{f.desc}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>

          {/* 4. Error Summary Banner */}
          <div className="error-summary-banner">
            <div className="error-summary-info">
              <div>
                <strong style={{ fontSize: '0.88rem', color: 'var(--text)', display: 'block' }}>
                  {isEn ? 'Key Error Cases for this Route:' : 'أبرز حالات الأخطاء لهذا المسار:'}
                </strong>
                <div style={{ display: 'flex', gap: '0.4rem', marginTop: '0.35rem' }}>
                  {endpoint.rules && endpoint.rules.map((rule, i) => (
                    <span 
                      key={i} 
                      className="badge-pill badge-req" 
                      style={{ cursor: 'pointer', display: 'inline-flex', alignItems: 'center', gap: '0.25rem' }}
                      title={isEn ? 'Click to open Error Dictionary' : 'اضغط لفتح القاموس الشامل'}
                      onClick={onOpenErrorDictionary}
                    >
                      <AlertTriangle size={12} /> {rule.err}
                    </span>
                  ))}
                </div>
              </div>
            </div>
            <button className="btn-open-error-dict" onClick={onOpenErrorDictionary}>
              <span>{isEn ? 'Comprehensive Error Dictionary (HTTP & 10xxx) →' : 'القاموس الشامل لرموز وأكواد الأخطاء (HTTP & Custom 10xxx) ←'}</span>
            </button>
          </div>
        </div>
      )}

      {/* PANE 2: FULL WORKING EXAMPLE & CODE PLAYGROUND */}
      {activeTab === 'example' && (
        <div className="full-example-grid">
          {/* Column 1: Full Request Example */}
          <div className="example-box-card">
            <div className="example-box-header">
              <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem' }}>
                <strong style={{ fontSize: '0.85rem', color: 'var(--text)' }}>
                  {isEn ? 'Full Wire Request' : 'الطلب الكامل (Full Wire Request)'}
                </strong>
                <span className="badge-pill badge-iso">
                  {endpoint.method} / {currentExampleFormat.toUpperCase()}
                </span>
              </div>
              <button 
                className="btn btn-ghost" 
                style={{ padding: '0.2rem 0.55rem', fontSize: '0.75rem' }} 
                onClick={() => handleCopy(getFormattedPayload(), 'req')}
              >
                {copiedReq ? <Check size={13} style={{ color: 'var(--emerald)' }} /> : <Copy size={13} />}
                <span>{isEn ? `Copy Request (${currentExampleFormat.toUpperCase()})` : `نسخ الطلب (${currentExampleFormat.toUpperCase()})`}</span>
              </button>
            </div>
            <div className="example-code-pane">
              {getFormattedPayload()}
            </div>
          </div>

          {/* Column 2: Full Response Example */}
          <div className="example-box-card">
            <div className="example-box-header">
              <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem' }}>
                <strong style={{ fontSize: '0.85rem', color: 'var(--text)' }}>
                  {isEn ? 'Full Wire Response' : 'الاستجابة الكاملة (Full Wire Response)'}
                </strong>
                <span className="badge-pill badge-fin">
                  HTTP 200 / {currentExampleFormat.toUpperCase()}
                </span>
              </div>
              <button 
                className="btn btn-ghost" 
                style={{ padding: '0.2rem 0.55rem', fontSize: '0.75rem' }} 
                onClick={() => handleCopy(getFormattedResponse(), 'res')}
              >
                {copiedRes ? <Check size={13} style={{ color: 'var(--emerald)' }} /> : <Copy size={13} />}
                <span>{isEn ? `Copy Response (${currentExampleFormat.toUpperCase()})` : `نسخ الاستجابة (${currentExampleFormat.toUpperCase()})`}</span>
              </button>
            </div>
            <div className="example-code-pane" style={{ color: '#a7f3d0' }}>
              {getFormattedResponse()}
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
